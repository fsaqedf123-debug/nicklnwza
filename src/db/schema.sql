-- Evaluation Rounds: controls academic year, semester, open/close status
CREATE TABLE IF NOT EXISTS evaluation_rounds (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  round_code TEXT UNIQUE NOT NULL,       -- e.g. '2568-1'
  academic_year INTEGER NOT NULL,        -- e.g. 2568 (Admin configured, not hardcoded)
  semester INTEGER NOT NULL,             -- 1 or 2 or 3
  title TEXT NOT NULL,                   -- e.g. 'ภาคการศึกษาที่ 1 ปีการศึกษา 2568'
  status TEXT NOT NULL DEFAULT 'open',   -- 'open' or 'closed'
  form_version TEXT NOT NULL DEFAULT 'v2', -- 'v1' or 'v2'
  notes TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Master Table for Question Definitions (preserves permanent codes and versions)
CREATE TABLE IF NOT EXISTS question_definitions (
  code TEXT PRIMARY KEY,                 -- Permanent code, never changes across versions
  section_num TEXT NOT NULL,             -- '4.1', '4.2', '4.3', '4.4', '4.5', '4.6', '4.7'
  category TEXT NOT NULL,                -- e.g. 'prep_clinical', 'early_childhood', 'ward', etc.
  title_th TEXT NOT NULL,                -- Item main label / title
  subtitle_th TEXT,                      -- Detailed question description
  station_code TEXT,                     -- Station code if clinical teaching
  station_name_th TEXT,
  hospital_code TEXT,                    -- Hospital code if ward evaluation
  ward_code TEXT,                        -- Ward code if ward evaluation
  is_rating INTEGER NOT NULL DEFAULT 1,  -- 1 if rated 1-5 or N/A, 0 if text
  introduced_in_version TEXT NOT NULL DEFAULT 'v1', -- 'v1' or 'v2'
  sort_order INTEGER NOT NULL DEFAULT 0
);

-- Hospitals and Wards definitions
CREATE TABLE IF NOT EXISTS hospital_definitions (
  code TEXT PRIMARY KEY,
  name_th TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ward_definitions (
  code TEXT PRIMARY KEY,                 -- e.g. 'WARD_PSU_NICU', 'WARD_HY_NICU', 'WARD_SK_NICU'
  hospital_code TEXT NOT NULL REFERENCES hospital_definitions(code),
  ward_name_th TEXT NOT NULL,            -- e.g. 'หออภิบาลทารกแรกเกิด (NICU)'
  short_code TEXT,                       -- e.g. 'มอ1', 'NICU'
  sort_order INTEGER NOT NULL DEFAULT 0
);

-- Submissions: Anonymous student evaluation submissions
CREATE TABLE IF NOT EXISTS submissions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  submission_token TEXT UNIQUE NOT NULL, -- Idempotency token generated by client / uuid
  round_id INTEGER NOT NULL REFERENCES evaluation_rounds(id),
  form_version TEXT NOT NULL,            -- Form version at time of submission ('v1' or 'v2')
  section TEXT NOT NULL,                 -- 'Sec 01', 'Sec 02', 'Sec 03', 'Sec 04'
  submitted_at TEXT NOT NULL,            -- ISO 8601 string
  ip_hash TEXT,                          -- SHA-256 hash of IP for abuse prevention (never store raw IP)
  is_test_data INTEGER NOT NULL DEFAULT 0, -- 1 for simulated/test data, 0 for real data
  
  -- Section 4.2 Early childhood training status
  early_childhood_trained TEXT NOT NULL, -- 'trained' or 'not_trained'
  early_childhood_general_suggestion TEXT,

  -- Section 4.3 Ward training status
  ward_training_status TEXT NOT NULL,    -- 'trained' or 'not_trained' ('not_trained' if 'ไม่ได้ขึ้นฝึกบนหอผู้ป่วย')
  selected_wards_json TEXT NOT NULL,     -- JSON array of selected ward codes

  -- Section 4.7 Open-ended suggestions
  impressions_to_keep TEXT,              -- สิ่งที่ท่านประทับใจหรือเห็นว่าควรคงไว้
  improvements_and_suggestions TEXT      -- สิ่งที่ควรปรับปรุงและข้อเสนอแนะ
);

-- Answers: Every question answered per submission
CREATE TABLE IF NOT EXISTS submission_answers (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  submission_id INTEGER NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  question_code TEXT NOT NULL REFERENCES question_definitions(code),
  section_num TEXT NOT NULL,             -- '4.1' .. '4.7'
  
  -- Status:
  -- 'answered' = has score 1-5
  -- 'na' = user explicitly selected N/A
  -- 'not_trained' = skipped because user didn't train at that ward or early childhood
  -- 'not_in_version' = question didn't exist in that submission's version (e.g. 4.4, 4.5 in v1)
  status TEXT NOT NULL,
  
  score INTEGER,                         -- 1, 2, 3, 4, 5, or NULL for na/not_trained/not_in_version
  comment TEXT,                          -- Mandatory if score <= 3 (non-empty), optional for 4, 5, na
  metadata_json TEXT                     -- Context info (hospital name, ward name, station name)
);

-- Admin Accounts: For course coordinators and instructors
CREATE TABLE IF NOT EXISTS admins (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'coordinator',
  created_at TEXT NOT NULL
);

-- Indexes for lightning fast queries and filtering
CREATE INDEX IF NOT EXISTS idx_subs_round_section ON submissions(round_id, section);
CREATE INDEX IF NOT EXISTS idx_subs_submitted ON submissions(submitted_at);
CREATE INDEX IF NOT EXISTS idx_subs_is_test ON submissions(is_test_data);
CREATE INDEX IF NOT EXISTS idx_answers_sub ON submission_answers(submission_id);
CREATE INDEX IF NOT EXISTS idx_answers_qcode ON submission_answers(question_code);
CREATE INDEX IF NOT EXISTS idx_answers_status ON submission_answers(status);
CREATE INDEX IF NOT EXISTS idx_answers_score ON submission_answers(score);
CREATE INDEX IF NOT EXISTS idx_answers_section ON submission_answers(section_num);
